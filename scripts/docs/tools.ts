// Regenerates the tools table in README.md from toolDefinitions.
// `pnpm docs:tools` rewrites it; `pnpm docs:tools --check` fails if it is out of date.
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { toolDefinitions } from '../../packages/shared/src/tools.ts';

const START = '<!-- tools:start (generated by `pnpm docs:tools`, do not edit) -->';
const END = '<!-- tools:end -->';
const readme = path.resolve(import.meta.dirname, '../../README.md');

/** First sentence of a tool description, as a table cell. */
function summary(description: string): string {
  const first = /^.*?\.(?=\s+[A-Z]|$)/s.exec(description)?.[0] ?? description;
  return first
    .replace(/,? e\.g\..*$/s, '.')
    .replace(/\s+/g, ' ')
    .replaceAll('|', '\\|');
}

/** Padded like Prettier formats Markdown tables, so `pnpm format:check` agrees with it. */
export function toolsTable(): string {
  const rows = Object.values(toolDefinitions).map((tool) => [
    `\`${tool.name}\``,
    summary(tool.description),
  ]);
  const header = ['Tool', 'What it does'];
  const widths = header.map((h, i) => Math.max(h.length, ...rows.map((row) => row[i]!.length)));
  const line = (cells: string[]) =>
    `| ${cells.map((cell, i) => cell.padEnd(widths[i]!)).join(' | ')} |`;
  return [
    line(header),
    `| ${widths.map((w) => '-'.repeat(w)).join(' | ')} |`,
    ...rows.map(line),
  ].join('\n');
}

const text = await readFile(readme, 'utf8');
const start = text.indexOf(START);
const end = text.indexOf(END);
if (start === -1 || end === -1 || end < start) {
  console.error(`README.md is missing the ${START} / ${END} markers.`);
  process.exit(1);
}
const next = `${text.slice(0, start + START.length)}\n\n${toolsTable()}\n\n${text.slice(end)}`;

if (process.argv.includes('--check')) {
  if (next !== text) {
    console.error('The tools table in README.md is out of date. Run `pnpm docs:tools`.');
    process.exit(1);
  }
  console.log('README tools table is up to date.');
} else {
  await writeFile(readme, next);
  console.log('README tools table updated.');
}
